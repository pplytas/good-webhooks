// Writes api-report.md: every export of every entry point, printed from the built .d.ts files.
// `--check` compares instead of writing, so CI fails when an export changes without the report.
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SyntaxKind } from 'typescript/unstable/ast'
import { API, SymbolFlags } from 'typescript/unstable/sync'

const packageDir = fileURLToPath(new URL('..', import.meta.url))
const reportPath = join(packageDir, 'api-report.md')
const regenerate = 'pnpm --filter good-webhooks api-report'

const { exports } = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'))
const entries = Object.entries(exports)
  .filter(([, target]) => typeof target === 'object' && target.types)
  .map(([subpath, target]) => ({
    name: subpath === '.' ? 'good-webhooks' : `good-webhooks/${subpath.slice(2)}`,
    file: join(packageDir, target.types),
  }))

const report = generate(entries)

if (process.argv.includes('--check')) {
  const committed = readFileSync(reportPath, 'utf8')
  if (committed !== report) {
    console.error(`api-report.md is stale. Regenerate it with \`${regenerate}\` and commit it.\n`)
    console.error(diff(committed, report))
    process.exit(1)
  }
  console.log('api-report.md is up to date.')
} else {
  writeFileSync(reportPath, report)
  console.log(`Wrote api-report.md (${entries.length} entry points).`)
}

function generate(entries) {
  // A throwaway tsconfig keeps the program to the entry files and their imports.
  const configDir = mkdtempSync(join(tmpdir(), 'good-webhooks-api-report-'))
  const configPath = join(configDir, 'tsconfig.json')
  writeFileSync(
    configPath,
    JSON.stringify({
      compilerOptions: {
        noEmit: true,
        skipLibCheck: true,
        strict: true,
        module: 'NodeNext',
        moduleResolution: 'NodeNext',
        types: [],
      },
      files: entries.map((entry) => entry.file),
    }),
  )
  const api = new API({ cwd: packageDir })
  try {
    const project = api.updateSnapshot({ openProjects: [configPath] }).getProjects()[0]
    const { checker, emitter, program } = project
    const sections = entries.map((entry) => {
      const sourceFile = program.getSourceFile(entry.file)
      if (!sourceFile) throw new Error(`${entry.file} is missing. Run the build first.`)
      const blocks = checker
        .getExportsOfModule(checker.getSymbolAtLocation(sourceFile))
        .map((symbol) => {
          const target =
            symbol.flags & SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
          const alias = target.name !== symbol.name ? ` (alias of ${target.name})` : ''
          const declarations = target.declarations.map((handle) => {
            const node = handle.resolve(project)
            // A variable declaration prints without `export declare const`; print its statement.
            const printed = node.kind === SyntaxKind.VariableDeclaration ? node.parent.parent : node
            return emitter.printNode(printed)
          })
          return {
            name: symbol.name,
            text: `### ${symbol.name}${alias}\n\n\`\`\`ts\n${declarations.join('\n')}\n\`\`\``,
          }
        })
        .sort((a, b) => a.name.localeCompare(b.name, 'en'))
      return `## ${entry.name}\n\n${blocks.map((block) => block.text).join('\n\n')}`
    })
    return (
      [
        '# good-webhooks API report',
        `Generated by scripts/api-report.mjs; regenerate with \`${regenerate}\`; CI fails when it is stale.`,
        ...sections,
      ].join('\n\n') + '\n'
    )
  } finally {
    api.close()
    rmSync(configDir, { recursive: true, force: true })
  }
}

function diff(before, after) {
  const dir = mkdtempSync(join(tmpdir(), 'good-webhooks-api-report-'))
  try {
    writeFileSync(join(dir, 'committed'), before)
    writeFileSync(join(dir, 'generated'), after)
    const result = spawnSync('diff', ['-u', 'committed', 'generated'], {
      cwd: dir,
      encoding: 'utf8',
    })
    if (result.stdout) return result.stdout
    // No diff binary: show the first line that differs.
    const a = before.split('\n')
    const b = after.split('\n')
    const line = a.findIndex((text, index) => text !== b[index])
    const at = line === -1 ? a.length : line
    return `First difference at line ${at + 1}:\n- ${a[at] ?? ''}\n+ ${b[at] ?? ''}`
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}
